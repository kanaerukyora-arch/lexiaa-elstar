-- LEXIAA access-request inbox
create table if not exists public.lexiaa_access_messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  sender_email text,
  message text not null check (char_length(message) between 1 and 2000),
  access_granted boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.lexiaa_access_messages enable row level security;

revoke all on public.lexiaa_access_messages from anon, authenticated;
grant select on public.lexiaa_access_messages to authenticated;

drop policy if exists "LEXIAA admin can read access messages" on public.lexiaa_access_messages;
create policy "LEXIAA admin can read access messages"
on public.lexiaa_access_messages
for select
to authenticated
using ((auth.jwt() ->> 'email') = 'fathanmufadhil04@gmail.com');
